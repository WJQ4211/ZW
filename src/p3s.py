def _is_noise(paragraph: str) -> bool:
    value = paragraph.strip()
    return any(pattern.search(value) for pattern in NOISE_PATTERNS)


def _prepare_document(source: dict[str, str]) -> P3SDocument:
    text_path = ROOT / source["text_path"]
    if not text_path.is_file():
        raise P3SError(f"P2S source text is missing: {text_path}")
    actual_sha = sha256_file(text_path)
    if actual_sha != source["text_sha256"]:
        raise P3SError(f"P2S source text hash mismatch: {source['source_id']}")
    raw = text_path.read_text(encoding="utf-8")
    pieces = raw.split("\n\n")
    kept: list[tuple[str, int, int]] = []
    search_from = 0
    for piece in pieces:
        start = raw.find(piece, search_from)
        if start < 0:
            raise P3SError(f"paragraph source offset cannot be resolved: {source['source_id']}")
        search_from = start + len(piece)
        paragraph = piece.strip("\r\n")
        if _is_noise(paragraph) or not paragraph.strip() or paragraph.strip() == "&nbsp;":
            continue
        left_trimmed = paragraph.lstrip()
        raw_start = start + len(paragraph) - len(left_trimmed)
        raw_end = start + len(paragraph.rstrip())
        kept.append((paragraph.strip(), raw_start, raw_end))
    cleaned_text = "\n\n".join(item[0] for item in kept)
    segments: list[SourceSegment] = []
    paragraph_map: list[dict[str, Any]] = []
    cleaned_offset = 0
    for index, (paragraph, raw_start, raw_end) in enumerate(kept, start=1):
        locator = f"web_paragraph_{index:04d}"
        cleaned_start = cleaned_offset
        cleaned_end = cleaned_start + len(paragraph)
        cleaned_offset = cleaned_end + 2
        segment = SourceSegment(
            source_id=source["source_id"],
            source_locator=locator,
            text=paragraph,
            section_title="web_body",
            machine_extracted_anchor=locator,
            visual_review_required=False,
            extraction_status="extracted",
        )
        segments.append(segment)
        paragraph_map.append(
            {
                "source_id": source["source_id"],
                "paragraph_id": locator,
                "source_text_path": source["text_path"],
                "source_text_sha256": actual_sha,
                "character_start": raw_start,
                "character_end": raw_end,
                "cleaned_body_character_start": cleaned_start,
                "cleaned_body_character_end": cleaned_end,
                "text": paragraph,
                "preprocessing": "retained_exact_text",
            }
        )
    if not segments:
        raise P3SError(f"no usable paragraphs after permitted noise removal: {source['source_id']}")
    return P3SDocument(source=source, segments=tuple(segments), paragraph_map=tuple(paragraph_map), source_text_sha256=actual_sha)


def _load_canonical() -> tuple[list[dict[str, Any]], str]:
    actual_sha = sha256_file(CANONICAL_PATH)
    if actual_sha != CANONICAL_SHA256:
        raise P3SError(f"canonical SHA-256 mismatch: {actual_sha}")
    values = [json.loads(line) for line in CANONICAL_PATH.read_text(encoding="utf-8").splitlines() if line.strip()]
    if len(values) != 60 or len({value["evidence_id"] for value in values}) != 60:
        raise P3SError("canonical Evidence baseline is not 60 unique records")
    return values, actual_sha


