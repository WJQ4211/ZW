def _parse_json(content: str) -> Any:
    value = content.strip()
    fenced = re.fullmatch(r"```(?:json)?\s*(.*?)\s*```", value, flags=re.IGNORECASE | re.DOTALL)
    if fenced:
        value = fenced.group(1).strip()
    return json.loads(value)


def _parse_p3s_candidate(value: Any, source_id: str) -> tuple[EvidenceCandidate, str]:
    if not isinstance(value, dict) or set(value) != P3S_MODEL_FIELDS:
        raise ValueError("candidate_fields_must_match_p3s_strict_schema")
    core = {"source_id": source_id}
    core.update({key: value[key] for key in P3S_MODEL_FIELDS if key != "possible_corroboration_group"})
    candidate = model_validate(EvidenceCandidate, core)
    corroboration = value.get("possible_corroboration_group")
    if not isinstance(corroboration, str):
        raise ValueError("possible_corroboration_group_must_be_string")
    return candidate, corroboration


def _candidate_dict(candidate: EvidenceCandidate, corroboration: str = "") -> dict[str, Any]:
    value = model_dump(candidate)
    value["possible_corroboration_group"] = corroboration
    return value


def _is_chinese(value: str) -> bool:
    return bool(re.search(r"[\u3400-\u9fff]", value))


def _deterministic_validation(
    candidate: EvidenceCandidate,
    corroboration: str,
    document: P3SDocument,
    segment_map: dict[str, SourceSegment],
    existing: list[dict[str, Any]],
    seen: list[dict[str, Any]],
) -> list[str]:
    reasons: list[str] = []
    if candidate.source_id != document.source["source_id"]:
        reasons.append("source_id_mismatch")
    segment = segment_map.get(candidate.source_locator)
    if segment is None:
        reasons.append("source_locator_not_found")
    elif candidate.excerpt_original not in segment.text:
        reasons.append("excerpt_not_continuous_exact_match")
    if not candidate.excerpt_zh.strip():
        reasons.append("excerpt_zh_empty")
    if not _is_chinese(candidate.normalized_claim):
        reasons.append("normalized_claim_not_chinese")
    if candidate.evidence_nature not in ALLOWED_NATURES:
        reasons.append("evidence_nature_invalid")
    if not candidate.coding_dimensions:
        reasons.append("coding_dimensions_empty")
    if len(candidate.coding_dimensions) != len(set(candidate.coding_dimensions)):
        reasons.append("coding_dimensions_duplicate")
    if set(candidate.coding_dimensions) - ALLOWED_DIMENSIONS:
        reasons.append("coding_dimensions_invalid")
    if re.search(r"(本报告认为|某机构指出|该报告指出|来源认为)", candidate.normalized_claim):
        reasons.append("normalized_claim_source_attribution_prefix")
    if candidate.evidence_nature in {"test_result", "deployment_event"} and re.search(r"\b(?:aim|seek|will|plan|planned|intend|expected|goal)\b", candidate.excerpt_original, re.I):
        reasons.append("plan_or_intent_coded_as_result")
    normalized_excerpt = normalize_for_match(candidate.excerpt_original).casefold()
    if any(normalized_excerpt == normalize_for_match(item.get("excerpt_original", "")).casefold() for item in existing):
        reasons.append("duplicate_existing_canonical_excerpt")
    for item in seen:
        other = normalize_for_match(item["excerpt_original"]).casefold()
        if normalized_excerpt == other or normalized_excerpt in other or other in normalized_excerpt or difflib.SequenceMatcher(None, normalized_excerpt, other).ratio() >= 0.92:
            reasons.append("duplicate_or_over_split_within_p3s")
            break
    if not isinstance(corroboration, str):
        reasons.append("possible_corroboration_group_invalid")
    return sorted(set(reasons))


def _parse_semantic_response(value: Any) -> tuple[dict[int, dict[str, Any]], str | None]:
    if not isinstance(value, list):
        return {}, "semantic_response_not_array"
    allowed = {"candidate_index", "status", "reason", "claim_supported", "nature_supported", "dimension_reviews", "revised_fields"}
    result: dict[int, dict[str, Any]] = {}
    for item in value:
        if not isinstance(item, dict) or set(item) != allowed:
            return {}, "semantic_review_schema_invalid"
        if not isinstance(item["candidate_index"], int) or item["status"] not in {"accept", "revise", "reject"}:
            return {}, "semantic_review_value_invalid"
        if not isinstance(item["claim_supported"], bool) or not isinstance(item["nature_supported"], bool):
            return {}, "semantic_support_flags_invalid"
        reviews = item["dimension_reviews"]
        if not isinstance(reviews, list):
            return {}, "dimension_reviews_not_array"
        for review in reviews:
            if not isinstance(review, dict) or set(review) != {"dimension", "supported", "supporting_span", "reason"}:
                return {}, "dimension_review_schema_invalid"
            if review["dimension"] not in ALLOWED_DIMENSIONS or not isinstance(review["supported"], bool):
                return {}, "dimension_review_value_invalid"
        revised = item["revised_fields"]
        if not isinstance(revised, dict) or set(revised) - REVISION_FIELDS:
            return {}, "revised_fields_invalid"
        result[item["candidate_index"]] = item
    return result, None


def _apply_revision(candidate: EvidenceCandidate, review: dict[str, Any]) -> tuple[EvidenceCandidate, list[str]]:
    updates = dict(review.get("revised_fields", {}))
    if review.get("status") == "revise" and not updates:
        raise ValueError("revise_without_allowed_revised_fields")
    if set(updates) - REVISION_FIELDS:
        raise ValueError("revision_attempted_for_forbidden_field")
    data = _candidate_dict(candidate, "")
    data.update(updates)
    data.pop("possible_corroboration_group", None)
    revised = model_validate(EvidenceCandidate, data)
    return revised, sorted(updates)


