        f"VERSION: {template['version']}",
        f"BATCH_ID: {batch_id}",
        f"SOURCE_ID: {document.source['source_id']}",
        f"RESEARCH_QUESTION: {template['research_question']}",
        "TASK: Extract zero or more directly auditable atomic evidence candidates from this one source only. There is no minimum quantity.",
        "INPUT LIMIT: Use only the supplied source paragraphs. Do not use other sources, prior outputs, search results, or outside knowledge.",
        "OUTPUT: strict JSON array; every object must contain exactly eight fields and no others: source_locator, excerpt_original, excerpt_zh, normalized_claim, evidence_nature, coding_dimensions, topics, possible_corroboration_group.",
        "Do not produce any deterministic metadata such as case_id, source_grade, published_at, publisher, title, URL, evidence_id, version, or content_hash.",
