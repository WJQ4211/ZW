def checkpoint_identity(
    run_id: str,
    source_text_sha256: dict[str, str],
    extraction_prompt_template_sha256: str,
    semantic_prompt_template_sha256: str,
) -> dict[str, Any]:
    """Return the complete identity required before reusing a response."""
    return {
        "run_id": run_id,
        "source_text_sha256": dict(sorted(source_text_sha256.items())),
        "extraction_prompt_template_sha256": extraction_prompt_template_sha256,
        "semantic_prompt_template_sha256": semantic_prompt_template_sha256,
    }


def checkpoint_reuse_allowed(
    checkpoint: dict[str, Any],
    expected_identity: dict[str, Any],
    batch_id: str,
    expected_prompt_sha256: str,
    *,
    run_dir: Path | None = None,
    phase: str | None = None,
) -> bool:
    """Permit exact completed-batch reuse, including from a failed checkpoint."""
    if checkpoint.get("status") not in {"in_progress", "failed"}:
        return False
    if checkpoint.get("checkpoint_identity") != expected_identity:
        return False
    if batch_id not in checkpoint.get("completed_batches", []):
        return False
    prompt_hashes = checkpoint.get("prompt_sha256_by_batch")
    if not isinstance(prompt_hashes, dict) or prompt_hashes.get(batch_id) != expected_prompt_sha256:
        return False
    records = checkpoint.get("call_records", {})
    if not isinstance(records, dict) or batch_id not in records or not isinstance(records[batch_id], dict):
        return False
    record = records[batch_id]
    if record.get("prompt_sha256") != expected_prompt_sha256:
        return False
    if run_dir is not None:
        if phase not in {"extraction", "semantic"}:
            return False
        subdirectory = "extraction" if phase == "extraction" else "semantic"
        response_path = run_dir / "raw_model_outputs" / subdirectory / f"{batch_id}.json"
        if not response_path.exists():
            return False
        try:
            payload = json.loads(response_path.read_text(encoding="utf-8"))
            content = chat_completion_content(payload)
        except (OSError, UnicodeDecodeError, json.JSONDecodeError, ValueError):
            return False
        if record.get("response_content_sha256") != sha256_bytes(content.encode("utf-8")):
            return False
        expected_record_phase = "extraction" if phase == "extraction" else "same_model_separate_call_semantic_screening"
        if record.get("phase") != expected_record_phase:
            return False
    return True


def _load_checkpoint_response(
    run_dir: Path,
    checkpoint: dict[str, Any] | None,
    expected_identity: dict[str, Any],
    batch_id: str,
    phase: str,
    prompt_sha256: str,
) -> tuple[dict[str, Any], str, dict[str, Any]] | None:
    if checkpoint is None or not checkpoint_reuse_allowed(
        checkpoint,
        expected_identity,
        batch_id,
        prompt_sha256,
        run_dir=run_dir,
        phase=phase,
    ):
        return None
    subdirectory = "extraction" if phase == "extraction" else "semantic"
    response_path = run_dir / "raw_model_outputs" / subdirectory / f"{batch_id}.json"
    if not response_path.exists():
        return None
    payload = json.loads(response_path.read_text(encoding="utf-8"))
    content = chat_completion_content(payload)
    record = checkpoint["call_records"][batch_id]
    return payload, content, dict(record)


def _persist_checkpoint(
    run_dir: Path,
    identity: dict[str, Any],
    prompt_sha256_by_batch: dict[str, str],
    completed_batches: list[str],
    completed_stages: list[str],
    call_records: list[dict[str, Any]],
    *,
    failed: bool = False,
    status: str = "in_progress",
) -> None:
    if failed:
        status = "failed"
    _write_json(
        run_dir / "p3s_checkpoint.json",
        {
            "checkpoint_identity": identity,
            "prompt_sha256_by_batch": dict(sorted(prompt_sha256_by_batch.items())),
            "status": status,
            "completed_batches": sorted(set(completed_batches)),
            "completed_stages": sorted(set(completed_stages)),
            "call_records": {record["logical_batch_id"]: record for record in call_records if record.get("logical_batch_id")},
        },
    )


