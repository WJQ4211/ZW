def _output_hashes(run_dir: Path) -> dict[str, str]:
    return {
        _relative(path): sha256_file(path)
        for path in sorted(run_dir.rglob("*"))
        if path.is_file() and path.name != "p3s_manifest.json"
    }


def run_p3s(run_id: str, run_dir: Path, *, resume: bool = False, client_factory: Any | None = None) -> dict[str, Any]:
    if run_dir.exists() and any(run_dir.iterdir()) and not resume:
        raise P3SError("run_directory_not_empty_use_a_new_run_id_or_explicit_resume")
    run_dir.mkdir(parents=True, exist_ok=True)
    protected_before = _protected_output_hashes(run_dir)
    p2s_manifest = json.loads(P2S_MANIFEST.read_text(encoding="utf-8"))
    if p2s_manifest.get("input_canonical_sha256") != CANONICAL_SHA256:
        raise P3SError("P2S manifest canonical hash does not match required baseline")
    sources = _load_p2s_sources()
    canonical, canonical_sha = _load_canonical()
    documents = [_prepare_document(sources[source_id]) for source_id in SOURCE_IDS]
    extraction_template = _load_yaml(EXTRACTION_TEMPLATE)
    semantic_template = _load_yaml(SEMANTIC_TEMPLATE)

    paragraph_map = [mapping for document in documents for mapping in document.paragraph_map]
    _write_jsonl(run_dir / "paragraph_anchor_map.jsonl", paragraph_map)
    prompt_dir = run_dir / "prompt_packets"
    prompt_dir.mkdir(exist_ok=True)
    extraction_prompts: dict[str, str] = {}
    for document in documents:
        batches = _chunk_segments(document.segments)
        if len(batches) != 1:
            raise P3SError(f"P3S requires one source-local batch for these materials: {document.source['source_id']}")
        batch_id = f"{document.source['source_id']}-extract-001"
        prompt = _build_extraction_prompt(document, extraction_template, batch_id)
        extraction_prompts[document.source["source_id"]] = prompt
        _write_json(prompt_dir / f"{batch_id}.json", {"batch_id": batch_id, "source_id": document.source["source_id"], "source_text_sha256": document.source_text_sha256, "prompt_sha256": sha256_bytes(prompt.encode("utf-8"))})
        (prompt_dir / f"{batch_id}.txt").write_text(prompt, encoding="utf-8")

    prompt_sha256_by_batch = {
        f"{document.source['source_id']}-extract-001": sha256_bytes(extraction_prompts[document.source["source_id"]].encode("utf-8"))
        for document in documents
    }
    checkpoint_id = checkpoint_identity(
        run_id,
        {document.source["source_id"]: document.source_text_sha256 for document in documents},
        sha256_file(EXTRACTION_TEMPLATE),
        sha256_file(SEMANTIC_TEMPLATE),
    )
    checkpoint_path = run_dir / "p3s_checkpoint.json"
    resume_checkpoint: dict[str, Any] | None = None
    if checkpoint_path.exists():
        if not resume:
            raise P3SError("checkpoint_exists_use_explicit_resume")
        resume_checkpoint = json.loads(checkpoint_path.read_text(encoding="utf-8"))
        if resume_checkpoint.get("status") == "completed":
            raise P3SError("completed_run_cannot_resume")
        if resume_checkpoint.get("checkpoint_identity") != checkpoint_id:
            raise P3SError("checkpoint_identity_mismatch_input_or_template_hash")
    elif resume:
        raise P3SError("resume_requested_but_checkpoint_missing")

    missing_env = [name for name in ("MODEL_API_BASE_URL", "MODEL_API_KEY", "MODEL_ID") if not os.environ.get(name)]
    base_manifest: dict[str, Any] = {
        "run_id": run_id,
        "case_id": CASE_ID,
        "stage": "P3S",
        "executed_at_utc": _now_utc(),
        "p2s_run_id": P2S_RUN_ID,
        "source_ids": list(SOURCE_IDS),
        "source_count": len(documents),
        "source_text_sha256": {document.source["source_id"]: document.source_text_sha256 for document in documents},
        "canonical_path": _relative(CANONICAL_PATH),
        "canonical_sha256": canonical_sha,
        "expected_canonical_sha256": CANONICAL_SHA256,
        "extraction_prompt_template_sha256": sha256_file(EXTRACTION_TEMPLATE),
        "extraction_prompt_template_version": extraction_template.get("version"),
        "semantic_prompt_template_sha256": sha256_file(SEMANTIC_TEMPLATE),
        "semantic_prompt_template_version": semantic_template.get("version"),
        "prompt_packet_count": len(extraction_prompts),
        "planned_extraction_batch_count": len(documents),
        "planned_semantic_screen_batch_count": len(documents),
        "logical_extraction_batch_count": 0,
        "logical_semantic_screen_batch_count": 0,
        "missing_model_environment_variables": missing_env,
        "prepare_completed": True,
        "p3s_executed": False,
        "formal_g1_supplement_executed": False,
        "evidence_inserted": 0,
        "hypothesis_inserted": 0,
        "p4_executed": False,
        "snapshot_frozen": False,
        "p5_executed": False,
        "t1_read": False,
        "author_actual_review_count": 0,
        "model_api_calls": 0,
        "provider_call_count": 0,
        "physical_retry_count": 0,
        "api_key_written": False,
        "git_head": _git_head(),
        "python_version": platform.python_version(),
        "protected_prior_outputs_unchanged": protected_before == _protected_output_hashes(run_dir),
    }
    if missing_env:
        base_manifest["stop_reason"] = "model_api_unavailable_at_prepare_stage"
        base_manifest["api_unavailable_missing_names_only"] = missing_env
        _write_json(run_dir / "p3s_manifest.json", base_manifest)
        (run_dir / "p3s_quality_report.md").write_text(
            "# P3S质量报告\n\n"
            "本运行已完成确定性输入校验、段落编号和提示包准备。由于当前进程未配置真实ModelClient所需环境变量，按协议停止在提示包阶段；未创建raw_model_outputs，未使用硬编码候选。\n\n"
            f"- 缺少环境变量名称：{', '.join(missing_env)}\n- API调用：0\n- Evidence新增：0\n- T1读取：false\n- P4/G1/P5：false\n",
            encoding="utf-8",
        )
        return base_manifest

    client = client_factory() if client_factory is not None else APIModelClient()
    raw_candidates: list[dict[str, Any]] = []
    validated_candidates: list[dict[str, Any]] = []
    final_candidates: list[dict[str, Any]] = []
    rejected: list[dict[str, Any]] = []
    deterministic_rows: list[dict[str, Any]] = []
    semantic_rows: list[dict[str, Any]] = []
    duplicate_rows: list[dict[str, Any]] = []
    call_log: list[dict[str, Any]] = []
    call_records: list[dict[str, Any]] = []
    completed_batches: list[str] = []
    completed_stages: list[str] = []
    semantic_skipped_no_valid_candidates = 0
    semantic_screened_candidate_count = 0
    candidate_count_limit_exceeded_batch_count = 0
    candidates_rejected_due_to_batch_limit = 0
    existing_by_id = {value["evidence_id"]: value for value in canonical}
    all_existing_excerpts = list(canonical)
    seen_by_source: dict[str, list[dict[str, Any]]] = {source_id: [] for source_id in SOURCE_IDS}
    rejection_counts: Counter[str] = Counter()

    for document in documents:
        source_id = document.source["source_id"]
        batch_id = f"{source_id}-extract-001"
        prompt = extraction_prompts[source_id]
        cached = _load_checkpoint_response(run_dir, resume_checkpoint, checkpoint_id, batch_id, "extraction", prompt_sha256_by_batch[batch_id])
        reused_checkpoint = cached is not None
        if cached is not None:
            payload, content, cached_record = cached
            call_record = dict(cached_record)
            call_record["reused_from_checkpoint"] = True
            call_record["logical_call_executed"] = False
        else:
            try:
                payload, content, record = client.call(prompt, temperature=0.0, max_tokens=6000)
            except Exception as exc:
                _persist_checkpoint(run_dir, checkpoint_id, prompt_sha256_by_batch, completed_batches, completed_stages, call_records, failed=True)
                _write_failure_manifest(
                    run_dir,
                    run_id,
                    stage="extraction",
                    source_id=source_id,
                    error=exc,
                    completed_logical_calls=len(call_records),
                    saved_batches=completed_batches,
                )
                raise
            call_record = record.as_dict()
            call_record["reused_from_checkpoint"] = False
            call_record["logical_call_executed"] = True
        call_record.update({"phase": "extraction", "logical_batch_id": batch_id, "prompt_sha256": sha256_bytes(prompt.encode("utf-8")), "response_content_sha256": sha256_bytes(content.encode("utf-8"))})
        call_records.append(call_record)
        call_log.append(call_record)
        if not reused_checkpoint:
            _write_json(run_dir / "raw_model_outputs" / "extraction" / f"{batch_id}.json", payload)
        _append_jsonl(run_dir / "model_call_log.jsonl", call_record)
        completed_batches.append(batch_id)
        completed_stages.append("extraction")
        _persist_checkpoint(run_dir, checkpoint_id, prompt_sha256_by_batch, completed_batches, completed_stages, call_records)
        try:
            values = _parse_json(content)
        except Exception:
            values = []
            rejected.append({"source_id": source_id, "batch_id": batch_id, "candidate_index": None, "candidate": None, "rejection_reasons": ["model_response_not_strict_json"]})
            rejection_counts["model_response_not_strict_json"] += 1
        if not isinstance(values, list):
            values = []
            rejected.append({"source_id": source_id, "batch_id": batch_id, "candidate_index": None, "candidate": None, "rejection_reasons": ["model_response_not_array"]})
            rejection_counts["model_response_not_array"] += 1
        segment_map = {segment.source_locator: segment for segment in document.segments}
        valid_candidates: list[tuple[EvidenceCandidate, str, SourceSegment, int]] = []
        count_limit_exceeded = candidate_count_exceeds_limit(values)
        if count_limit_exceeded:
            candidate_count_limit_exceeded_batch_count += 1
            candidates_rejected_due_to_batch_limit += len(values)
            rejected.append(
                {
                    "source_id": source_id,
                    "batch_id": batch_id,
                    "candidate_index": None,
                    "candidate_count": len(values),
                    "candidate": None,
                    "rejection_reasons": ["candidate_count_exceeds_limit"],
                }
            )
        for index, value in enumerate(values):
            actual_fields, missing_fields, extra_fields = _field_audit(value)
            raw_candidates.append(
                {
                    "source_id": source_id,
                    "batch_id": batch_id,
                    "candidate_index": index,
                    "candidate": value,
                    "actual_fields": actual_fields,
                    "missing_fields": missing_fields,
                    "extra_fields": extra_fields,
                }
            )
            reasons: list[str] = ["candidate_count_exceeds_limit"] if count_limit_exceeded else []
            candidate: EvidenceCandidate | None = None
            corroboration = ""
            segment: SourceSegment | None = None
            try:
                candidate, corroboration = _parse_p3s_candidate(value, source_id)
            except Exception as exc:
                reasons.append("schema_invalid")
                reasons.append(str(exc))
            if candidate is not None:
                segment = segment_map.get(candidate.source_locator)
                reasons.extend(_deterministic_validation(candidate, corroboration, document, segment_map, all_existing_excerpts, seen_by_source[source_id]))
            deterministic_rows.append(
                {
                    "source_id": source_id,
                    "batch_id": batch_id,
                    "candidate_index": index,
                    "actual_fields": json.dumps(actual_fields, ensure_ascii=False),
                    "missing_fields": json.dumps(missing_fields, ensure_ascii=False),
                    "extra_fields": json.dumps(extra_fields, ensure_ascii=False),
                    "schema_valid": str(candidate is not None and not count_limit_exceeded).lower(),
                    "exact_quote_match": str(candidate is not None and segment is not None and candidate.excerpt_original in segment.text).lower(),
                    "deterministic_pass": str(not reasons).lower(),
                    "reasons": json.dumps(sorted(set(reasons)), ensure_ascii=False),
                }
            )
            if reasons or candidate is None or segment is None:
                for reason in set(reasons):
                    # Batch-level overflow is reported in dedicated counters,
                    # and detailed Pydantic text is retained only on the row.
                    if reason == "candidate_count_exceeds_limit" or reason.startswith("1 validation error"):
                        continue
                    rejection_counts[reason] += 1
                rejected.append({"source_id": source_id, "batch_id": batch_id, "candidate_index": index, "candidate": value, "rejection_reasons": sorted(set(reasons or ["candidate_invalid"]))})
                continue
            seen_by_source[source_id].append(_candidate_dict(candidate, corroboration))
            valid_candidates.append((candidate, corroboration, segment, index))
            value_with_ids = _candidate_dict(candidate, corroboration)
            value_with_ids.update({"source_id": source_id, "source_locator": candidate.source_locator, "evidence_id": stable_evidence_id(source_id, candidate.source_locator, candidate.excerpt_original), "content_hash": sha256_bytes((source_id + "\n" + candidate.source_locator + "\n" + candidate.excerpt_original).encode("utf-8"))})
            validated_candidates.append(value_with_ids)
            duplicate_rows.append({"source_id": source_id, "source_locator": candidate.source_locator, "evidence_id": value_with_ids["evidence_id"], "existing_id_collision": str(value_with_ids["evidence_id"] in existing_by_id).lower(), "existing_exact_excerpt": str(any(normalize_for_match(candidate.excerpt_original).casefold() == normalize_for_match(item.get("excerpt_original", "")).casefold() for item in all_existing_excerpts)).lower(), "internal_duplicate": "false", "decision": "passed_deterministic_gate"})

        semantic_batch_id = f"{source_id}-semantic-001"
        skip_reason = semantic_skip_reason(valid_candidates)
        if skip_reason:
            semantic_skipped_no_valid_candidates += 1
            semantic_rows.append(
                {
                    "source_id": source_id,
                    "batch_id": semantic_batch_id,
                    "candidate_index": "",
                    "status": "skipped",
                    "claim_supported": "",
                    "nature_supported": "",
                    "reason": skip_reason,
                    "dimension_reviews": "[]",
                    "revised_fields": "{}",
                    "unsupported_dimensions_removed": "[]",
                }
            )
            completed_batches.append(semantic_batch_id)
            completed_stages.append("semantic_skipped_no_valid_candidates")
            _persist_checkpoint(run_dir, checkpoint_id, prompt_sha256_by_batch, completed_batches, completed_stages, call_records)
            continue
        semantic_screened_candidate_count += len(valid_candidates)
        review_items = [_candidate_dict(candidate, corroboration) for candidate, corroboration, _, _ in valid_candidates]
        semantic_prompt = _build_semantic_prompt(review_items, semantic_template, semantic_batch_id)
        semantic_prompt_sha256 = sha256_bytes(semantic_prompt.encode("utf-8"))
        prompt_sha256_by_batch[semantic_batch_id] = semantic_prompt_sha256
        cached = _load_checkpoint_response(run_dir, resume_checkpoint, checkpoint_id, semantic_batch_id, "semantic", semantic_prompt_sha256)
        reused_checkpoint = cached is not None
        if cached is not None:
            semantic_payload, semantic_content, cached_record = cached
            semantic_call_record = dict(cached_record)
            semantic_call_record["reused_from_checkpoint"] = True
            semantic_call_record["logical_call_executed"] = False
        else:
            try:
                semantic_payload, semantic_content, semantic_record = client.call(semantic_prompt, temperature=0.0, max_tokens=6000)
            except Exception as exc:
                _persist_checkpoint(run_dir, checkpoint_id, prompt_sha256_by_batch, completed_batches, completed_stages, call_records, failed=True)
                _write_failure_manifest(
                    run_dir,
                    run_id,
                    stage="same_model_separate_call_semantic_screening",
                    source_id=source_id,
                    error=exc,
                    completed_logical_calls=len(call_records),
                    saved_batches=completed_batches,
                )
                raise
            semantic_call_record = semantic_record.as_dict()
            semantic_call_record["reused_from_checkpoint"] = False
            semantic_call_record["logical_call_executed"] = True
        semantic_call_record.update({"phase": "same_model_separate_call_semantic_screening", "logical_batch_id": semantic_batch_id, "prompt_sha256": sha256_bytes(semantic_prompt.encode("utf-8")), "response_content_sha256": sha256_bytes(semantic_content.encode("utf-8"))})
        call_records.append(semantic_call_record)
        call_log.append(semantic_call_record)
        if not reused_checkpoint:
            _write_json(run_dir / "raw_model_outputs" / "semantic" / f"{semantic_batch_id}.json", semantic_payload)
        _append_jsonl(run_dir / "model_call_log.jsonl", semantic_call_record)
        completed_batches.append(semantic_batch_id)
        completed_stages.append("semantic_screening")
        _persist_checkpoint(run_dir, checkpoint_id, prompt_sha256_by_batch, completed_batches, completed_stages, call_records)
        try:
            semantic_value = _parse_json(semantic_content)
            semantic_map, semantic_error = _parse_semantic_response(semantic_value)
        except Exception:
            semantic_map, semantic_error = {}, "semantic_response_invalid"
        if semantic_error:
            rejection_counts[semantic_error] += len(valid_candidates) or 1
            for candidate, _, _, original_index in valid_candidates:
                rejected.append({"source_id": source_id, "batch_id": semantic_batch_id, "candidate_index": original_index, "candidate": _candidate_dict(candidate), "rejection_reasons": [semantic_error]})
        for local_index, (candidate, corroboration, segment, original_index) in enumerate(valid_candidates):
            review = semantic_map.get(local_index)
            if review is None:
                continue
            declared_dimensions = list(candidate.coding_dimensions)
            dimension_reviews = review.get("dimension_reviews", [])
            review_by_dimension = {item["dimension"]: item for item in dimension_reviews if isinstance(item, dict)}
            unsupported = [dimension for dimension in declared_dimensions if review_by_dimension.get(dimension, {}).get("supported") is not True]
            semantic_rows.append({"source_id": source_id, "batch_id": semantic_batch_id, "candidate_index": original_index, "status": review.get("status"), "claim_supported": review.get("claim_supported"), "nature_supported": review.get("nature_supported"), "reason": review.get("reason", ""), "dimension_reviews": json.dumps(dimension_reviews, ensure_ascii=False), "revised_fields": json.dumps(review.get("revised_fields", {}), ensure_ascii=False), "unsupported_dimensions_removed": json.dumps(unsupported, ensure_ascii=False)})
            if review.get("status") == "reject" or review.get("claim_supported") is not True or review.get("nature_supported") is not True:
                rejection_counts["semantic_claim_nature_or_relevance_reject"] += 1
                rejected.append({"source_id": source_id, "batch_id": semantic_batch_id, "candidate_index": original_index, "candidate": _candidate_dict(candidate, corroboration), "rejection_reasons": ["semantic_claim_nature_or_relevance_reject", review.get("reason", "")]})
                continue
            try:
                revised_candidate, applied_fields = _apply_revision(candidate, review)
            except Exception as exc:
                rejection_counts["semantic_revision_invalid"] += 1
                rejected.append({"source_id": source_id, "batch_id": semantic_batch_id, "candidate_index": original_index, "candidate": _candidate_dict(candidate, corroboration), "rejection_reasons": ["semantic_revision_invalid", str(exc)]})
                continue
            revised_reasons = _deterministic_validation(revised_candidate, corroboration, document, {item.source_locator: item for item in document.segments}, all_existing_excerpts, [])
            if unsupported:
                revised_candidate = model_validate(EvidenceCandidate, {**_candidate_dict(revised_candidate, corroboration), "coding_dimensions": [dimension for dimension in revised_candidate.coding_dimensions if dimension not in unsupported]})
                applied_fields = sorted(set(applied_fields) | {"coding_dimensions"})
            if not revised_candidate.coding_dimensions:
                revised_reasons.append("all_coding_dimensions_unsupported")
            if revised_reasons:
                rejection_counts["semantic_revised_candidate_failed_deterministic_gate"] += 1
                rejected.append({"source_id": source_id, "batch_id": semantic_batch_id, "candidate_index": original_index, "candidate": _candidate_dict(revised_candidate, corroboration), "rejection_reasons": sorted(set(revised_reasons))})
                continue
            record = _inject_metadata(revised_candidate, corroboration, document.source, segment, run_id, review)
            record["semantic_applied_revision_fields"] = applied_fields
            final_candidates.append(record)

