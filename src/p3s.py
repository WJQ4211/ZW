def _chunk_segments(segments: tuple[SourceSegment, ...], max_chars: int = 45000) -> list[list[SourceSegment]]:
    batches: list[list[SourceSegment]] = []
    current: list[SourceSegment] = []
    chars = 0
    for segment in segments:
        if current and chars + len(segment.text) > max_chars:
            batches.append(current)
            current = []
            chars = 0
        current.append(segment)
        chars += len(segment.text)
    if current:
        batches.append(current)
    return batches


